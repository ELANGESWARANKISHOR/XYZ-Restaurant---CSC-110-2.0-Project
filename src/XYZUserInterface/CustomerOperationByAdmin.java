    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String name = jTextField1.getText();
        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "select NIC to delete", "success", JOptionPane.WARNING_MESSAGE);

        } else {
            int option = JOptionPane.showConfirmDialog(this, "Do you wish to delete Customer details", "confirmation", JOptionPane.YES_NO_OPTION, JOptionPane.INFORMATION_MESSAGE);
            if (option == JOptionPane.YES_OPTION) {
                try {
                    pst = con.prepareStatement(" DELETE FROM `cust` WHERE name = ?");
                    pst.setString(1, name); 
            
                    pst.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "Table Deleted");

                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

