    public void loadTablesCustomers(){
        
        
        try {
            pst = con.prepareStatement("SELECT * FROM `cust`");
            ResultSet rs = pst.executeQuery();
            
            
            def = (DefaultTableModel)jTable1.getModel();
            def.setRowCount(0);
            
            while(rs.next()){
                Vector<String> v1 = new Vector<>();
                v1.add(rs.getString("name"));
                v1.add(rs.getString("nic"));
                v1.add(rs.getString("telno"));
                v1.add(rs.getString("email"));
                v1.add(rs.getString("password"));
                def.addRow(v1);
                
            }
            
        } catch (SQLException ex) {
            Logger.getLogger(TableOperationsByAdmin.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }
