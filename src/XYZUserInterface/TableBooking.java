    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        
        Date sdate1 = jDateChooser1.getDate();
        String stime = jComboBox2.getSelectedItem().toString();
        String etime = jComboBox3.getSelectedItem().toString();
        String capacity = jTextField4.getText();
        String tableid = jComboBox1.getSelectedItem().toString();
        
        String sdate = sdf.format(sdate1);
        String bookingid = jLabel8.getText();
        int startTime = Integer.parseInt(stime);
        int endTime = Integer.parseInt(etime);
        
        try {
            pst = con.prepareStatement("SELECT * FROM `booking` WHERE `tableid` = ? AND `date` = ? AND(`starttime` >= ? AND `endtime`<= ?)");
            
            pst.setString(1,tableid);
            pst.setString(2,sdate);
            pst.setInt(3,startTime);
            pst.setInt(4,endTime);
            
            ResultSet rs = pst.executeQuery();
            
            if (rs.next()) {
                JOptionPane.showMessageDialog(this, "Table Already Booked Try to reset and select another", "Success", JOptionPane.WARNING_MESSAGE);
            }
            else
            {
                
               pst = con.prepareStatement("INSERT INTO `booking`(`bookingid`,`date`,`starttime`,`endtime`,`capacity`,`tableid`) VALUES (?,?,?,?,?,?)");
               
               pst.setString(1, bookingid);
               pst.setString(2, sdate);
               pst.setInt(3,startTime);
               pst.setInt(4, endTime);
               pst.setString(5, capacity);
               pst.setString(6, tableid);
               pst.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "Your Booking Added Successfully \n"+bookingid+" is your booking id");
            
            autoID();
            }

            
        } catch (SQLException ex) {
            Logger.getLogger(TableBooking.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton4ActionPerformed

