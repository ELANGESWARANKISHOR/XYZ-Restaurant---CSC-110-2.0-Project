    public void autoID(){
        
        Statement st;
        try {
            st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(bookingid) FROM `booking`");
            rs.next();
            rs.getString("MAX(bookingid)");
            
            if(rs.getString("MAX(bookingid)") == null)
            {
                jLabel8.setText("B001");
            }
            else 
            {
                long id = Long.parseLong(rs.getString("MAX(bookingid)").substring(2,rs.getString("MAX(bookingid)").length()));
                id++;
                jLabel8.setText("B"+String.format("%03d", id));
            }
        } catch (SQLException ex) {
            Logger.getLogger(TableOperationsByAdmin.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }
    
    public void loadtables(String cap){
        
        try {
            pst = con.prepareStatement("SELECT tableid FROM `tab` WHERE capacity = ?");
            pst.setString(1, cap);
            ResultSet rs = pst.executeQuery();
            
            while(rs.next()){
                jComboBox1.addItem(rs.getString("tableid"));
            }
        } catch (SQLException ex) {
            Logger.getLogger(TableBooking.class.getName()).log(Level.SEVERE, null, ex);
        }
        
                
    }
    
    
