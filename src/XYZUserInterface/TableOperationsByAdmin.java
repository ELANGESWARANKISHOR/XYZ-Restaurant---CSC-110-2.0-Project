    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String tableid = jLabel4.getText();
        String capacity = jComboBox1.getSelectedItem().toString();
        String price = jTextField1.getText();
        
        try {
            pst = con.prepareStatement("UPDATE `tab` SET capacity = ?, price = ? where tableid = ?");
            pst.setString(1, capacity);
            pst.setString(2, price);
            pst.setString(3, tableid);
            pst.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "Table Edited");
            
            autoID();
            
            jComboBox1.setSelectedIndex(-1);
            jTextField1.setText("");
            jButton4.setEnabled(true);
            jButton2.setEnabled(true);
            
            
        } catch (SQLException ex) {
            Logger.getLogger(TableOperationsByAdmin.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

