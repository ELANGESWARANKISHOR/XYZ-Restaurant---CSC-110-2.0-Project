    public void autoID(){
        
        Statement st;
        try {
            st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(tableid) FROM `tab`");
            rs.next();
            rs.getString("MAX(tableid)");
            
            if(rs.getString("MAX(tableid)") == null)
            {
                jLabel4.setText("T0001");
            }
            else 
            {
                long id = Long.parseLong(rs.getString("MAX(tableid)").substring(2,rs.getString("MAX(tableid)").length()));
                id++;
                jLabel4.setText("T"+String.format("%03d", id));
            }
        } catch (SQLException ex) {
            Logger.getLogger(TableOperationsByAdmin.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }
    
    public void loadTables(){
        
        
        try {
            pst = con.prepareStatement("SELECT * FROM `tab`");
            ResultSet rs = pst.executeQuery();
            
            
            def = (DefaultTableModel)jTable2.getModel();
            def.setRowCount(0);
            
            while(rs.next()){
                Vector<String> v1 = new Vector<>();
                v1.add(rs.getString("tableid"));
                v1.add(rs.getString("capacity"));
                v1.add(rs.getString("price"));
                def.addRow(v1);
                
            }
            
        } catch (SQLException ex) {
            Logger.getLogger(TableOperationsByAdmin.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }
